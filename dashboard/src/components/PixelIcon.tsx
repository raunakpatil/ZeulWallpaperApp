const ICONS = {
  ...BASE,
  starEmpty: BASE.star.map((r) => r.replace(/y/g, 'c')),
  starOff: BASE.star.map((r) => r.replace(/y/g, 'g')),
  heartEmpty: BASE.heart.map((r) => r.replace(/[rw]/g, 'c')),
  chevronLeft: BASE.chevronRight.map((r) => [...r].reverse().join('')),
  arrowDown: [...BASE.arrowUp].reverse(),
};

export type PixelName = keyof typeof ICONS;

export function PixelIcon({ name, size = 24, className, style }: {
  name: PixelName; size?: number | string; className?: string; style?: CSSProperties;
}) {
  const rects: React.ReactNode[] = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== '.') rects.push(<rect key={`${y}-${x}`} x={x} y={y} width={end - x} height={1} style={{ fill: COLORS[ch] }} />);
      x = end;
    }
  });
  return (
    <svg className={`pixel-icon${className ? ` ${className}` : ''}`} style={style} width={size} height={size}
      viewBox="0 0 12 12" shapeRendering="crispEdges" aria-hidden focusable="false">
      {rects}
    </svg>
  );
}
